package mycompany.project1;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.ThreadLocalRandom;
import java.util.regex.Pattern;


public class Message {

    public static final int MAX_LENGTH = 250;

    // "+" then an international code (1-3 digits) then at most 10 more digits.
    private static final Pattern CELL_PATTERN = Pattern.compile("^\\+[0-9]{1,3}[0-9]{1,10}$");

    private static final List<Message> sentMessages = new ArrayList<>();
    private static final List<Message> storedMessages = new ArrayList<>();
    private static int messageCounter = 0;          // autogenerated "message number"
    private static Path storagePath = Paths.get("messages.json");

    private final String messageID;
    private final int messageNumber;
    private final String recipient;
    private final String messageText;
    private final String messageHash;

   
    public Message(String recipient, String messageText) {
        this(generateMessageID(), messageCounter++, recipient, messageText);
    }

    
    public Message(String messageID, int messageNumber, String recipient, String messageText) {
        this.messageID = messageID;
        this.messageNumber = messageNumber;
        this.recipient = recipient;
        this.messageText = messageText;
        this.messageHash = createMessageHash();
    }

    

   
    public boolean checkMessageID() {
        return messageID != null && messageID.length() <= 10;
    }

   
    public String checkRecipientCell() {
        return validateRecipient(recipient);
    }

    public static boolean isValidRecipient(String cell) {
        return cell != null && CELL_PATTERN.matcher(cell).matches();
    }

    public static String validateRecipient(String cell) {
        if (isValidRecipient(cell)) {
            return "Cell phone number successfully captured.";
        }
        return "Cell phone number is incorrectly formatted or does not contain an international code. "
                + "Please correct the number and try again.";
    }

    public static boolean isValidLength(String text) {
        return text != null && text.length() <= MAX_LENGTH;
    }

    public static String validateLength(String text) {
        if (isValidLength(text)) {
            return "Message ready to send.";
        }
        int over = (text == null ? 0 : text.length()) - MAX_LENGTH;
        return "Message exceeds 250 characters by " + over + "; please reduce the size.";
    }

   

    public String createMessageHash() {
        String text = messageText == null ? "" : messageText.trim();
        String first = "";
        String last = "";
        if (!text.isEmpty()) {
            String[] words = text.split("\\s+");
            first = clean(words[0]);
            last = clean(words[words.length - 1]);
        }
        String prefix = messageID.length() >= 2 ? messageID.substring(0, 2) : messageID;
        return (prefix + ":" + messageNumber + ":" + first + last).toUpperCase();
    }

    private static String clean(String word) {
        return word.replaceAll("[^A-Za-z0-9]", "");
    }

   

    public String SentMessage(int option) {
        switch (option) {
            case 1:
                sentMessages.add(this);
                return "Message successfully sent.";
            case 2:
                return "Press 0 to delete the message.";
            case 3:
                storedMessages.add(this);
                storeMessage();
                return "Message successfully stored.";
            default:
                return "Invalid option. Please choose 1, 2 or 3.";
        }
    }

 
    public static void storeMessage() {
        StringBuilder sb = new StringBuilder("[\n");
        for (int i = 0; i < storedMessages.size(); i++) {
            Message m = storedMessages.get(i);
            sb.append("  {\n")
              .append("    \"messageID\": \"").append(json(m.messageID)).append("\",\n")
              .append("    \"messageNumber\": ").append(m.messageNumber).append(",\n")
              .append("    \"messageHash\": \"").append(json(m.messageHash)).append("\",\n")
              .append("    \"recipient\": \"").append(json(m.recipient)).append("\",\n")
              .append("    \"message\": \"").append(json(m.messageText)).append("\"\n")
              .append("  }").append(i < storedMessages.size() - 1 ? "," : "").append("\n");
        }
        sb.append("]\n");
        try {
            Files.write(storagePath, sb.toString().getBytes(StandardCharsets.UTF_8));
        } catch (IOException e) {
            System.out.println("Could not write JSON file: " + e.getMessage());
        }
    }

    private static String json(String s) {
        StringBuilder out = new StringBuilder();
        for (char c : s.toCharArray()) {
            switch (c) {
                case '"':  out.append("\\\""); break;
                case '\\': out.append("\\\\"); break;
                case '\n': out.append("\\n");  break;
                case '\r': out.append("\\r");  break;
                case '\t': out.append("\\t");  break;
                default:   out.append(c);
            }
        }
        return out.toString();
    }

 

    public String details() {
        return "Message ID: " + messageID + "\n"
             + "Message Hash: " + messageHash + "\n"
             + "Recipient: " + recipient + "\n"
             + "Message: " + messageText;
    }

    
    public static String printMessages() {
        if (sentMessages.isEmpty()) {
            return "No messages have been sent yet.";
        }
        StringBuilder sb = new StringBuilder();
        for (Message m : sentMessages) {
            sb.append(m.details()).append("\n\n");
        }
        return sb.toString().trim();
    }

    public static int returnTotalMessages() {
        return sentMessages.size();
    }

    

    public static String generateMessageID() {
        return String.format("%010d", ThreadLocalRandom.current().nextLong(10_000_000_000L));
    }

    public String getMessageID() { return messageID; }
    public int getMessageNumber() { return messageNumber; }
    public String getRecipient() { return recipient; }
    public String getMessageText() { return messageText; }
    public String getMessageHash() { return messageHash; }

    public static void setStoragePath(Path path) { storagePath = path; }

   
    public static void reset() {
        sentMessages.clear();
        storedMessages.clear();
        messageCounter = 0;
    }
}